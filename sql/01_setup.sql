-- Replace YOUR_BUCKET, YOUR_ACCOUNT_ID and the role ARN before execution.
-- Use a Snowflake administrator for setup only. Runtime uses CHURN_POC_ROLE.
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS CHURN_POC_WH
  WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE DATABASE IF NOT EXISTS CHURN_POC_DB;
CREATE ROLE IF NOT EXISTS CHURN_POC_ROLE;
GRANT USAGE ON WAREHOUSE CHURN_POC_WH TO ROLE CHURN_POC_ROLE;
GRANT USAGE ON DATABASE CHURN_POC_DB TO ROLE CHURN_POC_ROLE;
GRANT USAGE ON SCHEMA CHURN_POC_DB.PUBLIC TO ROLE CHURN_POC_ROLE;
GRANT CREATE TABLE ON SCHEMA CHURN_POC_DB.PUBLIC TO ROLE CHURN_POC_ROLE;
-- Do not CREATE OR REPLACE an existing integration: its external ID may change.
CREATE STORAGE INTEGRATION IF NOT EXISTS CHURN_POC_S3
  TYPE=EXTERNAL_STAGE STORAGE_PROVIDER='S3' ENABLED=TRUE
  STORAGE_AWS_ROLE_ARN='arn:aws:iam::YOUR_ACCOUNT_ID:role/ChurnSnowflakeS3Role'
  STORAGE_ALLOWED_LOCATIONS=('s3://YOUR_BUCKET/churn-poc/');
GRANT USAGE ON INTEGRATION CHURN_POC_S3 TO ROLE CHURN_POC_ROLE;
DESC INTEGRATION CHURN_POC_S3;
